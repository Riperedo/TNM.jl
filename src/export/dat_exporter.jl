# Data Exporter and Gnuplot Script Generator

using Printf

"""
    export_dat(filepath::AbstractString, res::SimulationResult; 
               Cpg::Real=1.0, Cpl::Real=2.0, delta_Cp::Real=1.0)

Exports simulation results to a space-delimited `.dat` file with a leading `# header` comment line:
    # time_s temperature_K fictive_temp_K cp_normalized enthalpy heat_flow
"""
function export_dat(filepath::AbstractString, res::SimulationResult; 
                    Cpg::Real=1.0, Cpl::Real=2.0, delta_Cp::Real=1.0)
    t = res.times
    T = res.temperatures
    Tf = res.fictive_temperatures
    cp_n = normalized_heat_capacity(res)
    enth = enthalpy(res; Cpl=Cpl, delta_Cp=delta_Cp)
    hf = heat_flow(res; Cpg=Cpg, delta_Cp=delta_Cp)
    N = length(t)

    open(filepath, "w") do io
        # Header comment with property names
        println(io, "# time_s temperature_K fictive_temp_K cp_normalized enthalpy heat_flow")
        for i in 1:N
            @printf(io, "%16.8e %16.8e %16.8e %16.8e %16.8e %16.8e\n",
                    t[i], T[i], Tf[i], cp_n[i], enth[i], hf[i])
        end
    end
    return filepath
end

"""
    export_dat(filepath::AbstractString, res::TMDSCResult)

Exports Temperature-Modulated DSC analysis results to a `.dat` file:
    # time_s temperature_K cp_real cp_imag cp_modulus phase_deg
"""
function export_dat(filepath::AbstractString, res::TMDSCResult)
    N = length(res.times)
    open(filepath, "w") do io
        println(io, "# time_s temperature_K cp_real cp_imag cp_modulus phase_deg")
        for i in 1:N
            @printf(io, "%16.8e %16.8e %16.8e %16.8e %16.8e %16.8e\n",
                    res.times[i], res.temperatures[i], res.cp_real[i], 
                    res.cp_imag[i], res.cp_modulus[i], res.phase_deg[i])
        end
    end
    return filepath
end

"""
    export_dat(filepath::AbstractString, data::AbstractMatrix, headers::Vector{<:AbstractString})

Generic `.dat` file exporter for tabular numerical matrices.
"""
function export_dat(filepath::AbstractString, data::AbstractMatrix, headers::Vector{<:AbstractString})
    size(data, 2) == length(headers) || throw(DimensionMismatch("Headers length must match data columns"))
    open(filepath, "w") do io
        print(io, "#")
        for h in headers
            print(io, " ", h)
        end
        println(io)
        for row in 1:size(data, 1)
            for col in 1:size(data, 2)
                @printf(io, "%16.8e ", data[row, col])
            end
            println(io)
        end
    end
    return filepath
end

"""
    generate_gnuplot_script(dat_filename::AbstractString, gnu_filename::AbstractString;
                            title::AbstractString="TNM Simulation",
                            plot_type::Symbol=:cp_normalized)

Generates a standalone Gnuplot script (.gnu / .plt) tailored to visualize the exported `.dat` file.
Supported `plot_type` values:
- `:cp_normalized`: Normalized Heat Capacity Cp^N vs Temperature (column 2 vs 4).
- `:fictive_temperature`: Fictive Temperature Tf and T vs Time (column 1 vs 2 & 3).
- `:enthalpy`: Enthalpy vs Temperature (column 2 vs 5).
- `:tmdsc`: Complex Heat Capacity Modulus and Phase vs Temperature.
"""
function generate_gnuplot_script(dat_filename::AbstractString, gnu_filename::AbstractString;
                                title::AbstractString="TNM Structural Relaxation",
                                plot_type::Symbol=:cp_normalized)
    open(gnu_filename, "w") do io
        println(io, "# Gnuplot script generated by TNM.jl")
        println(io, "# Run interactively: gnuplot -p $(basename(gnu_filename))")
        println(io, "set grid")
        println(io, "set key top left")
        println(io, "set title '$(title)'")
        
        if plot_type === :cp_normalized
            println(io, "set xlabel 'Temperature T (K)'")
            println(io, "set ylabel 'Normalized Heat Capacity C_p^N'")
            println(io, "plot '$(basename(dat_filename))' using 2:4 with lines lw 2 lc rgb '#1f77b4' title 'C_p^N (T)'")
        elseif plot_type === :fictive_temperature
            println(io, "set xlabel 'Time t (s)'")
            println(io, "set ylabel 'Temperature (K)'")
            println(io, "plot '$(basename(dat_filename))' using 1:2 with lines lw 2 lc rgb '#d62728' title 'T(t)', \\")
            println(io, "     '$(basename(dat_filename))' using 1:3 with lines lw 2 lc rgb '#2ca02c' title 'T_f(t)'")
        elseif plot_type === :enthalpy
            println(io, "set xlabel 'Temperature T (K)'")
            println(io, "set ylabel 'Enthalpy H (J/g)'")
            println(io, "plot '$(basename(dat_filename))' using 2:5 with lines lw 2 lc rgb '#9467bd' title 'H(T)'")
        elseif plot_type === :tmdsc
            println(io, "set xlabel 'Temperature T (K)'")
            println(io, "set ylabel '|C_p^*| Modulus'")
            println(io, "set y2label 'Phase angle {/Symbol d} (deg)'")
            println(io, "set y2tics")
            println(io, "plot '$(basename(dat_filename))' using 2:5 with lines lw 2 lc rgb '#1f77b4' title '|C_p^*|', \\")
            println(io, "     '$(basename(dat_filename))' using 2:6 with lines lw 2 lc rgb '#ff7f0e' axes x1y2 title 'Phase {/Symbol d}'")
        end
    end
    return gnu_filename
end
